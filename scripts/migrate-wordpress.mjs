/**
 * One-off migration: pulls posts from the live WordPress site's REST API and
 * writes content/stories.ts + downloads featured images into public/img/stories.
 *
 *   node scripts/migrate-wordpress.mjs
 *
 * Re-runnable. Phase 3 replaces this with Supabase-backed admin CRUD, at which
 * point this script becomes the seed step and can be deleted.
 */
import { writeFile, mkdir } from "node:fs/promises";
import { createWriteStream } from "node:fs";
import { Readable } from "node:stream";
import { pipeline } from "node:stream/promises";
import path from "node:path";

const SITE = "https://bhutaneseincanberra.org.au";
const IMG_DIR = "public/img/stories";

/** WordPress slugs are percent-encoded mathematical-bold unicode — unusable in
 *  a URL bar. These are the hand-written replacements. */
const SLUGS = {
  "2026-06-29": "executive-handover-2026",
  "2025-07-16": "executive-handover-2025",
  "2024-12-18": "national-day-celebration",
  "2024-10-23": "royal-visit",
  "2024-09-22": "bhutanese-businesses-in-canberra",
  "2024-09-20": "royal-visit-to-australia",
  "2024-09-14": "abac-website-launch",
  "2024-08-30": "fundraising-party-2024",
  "2024-08-24": "volleyball-tournament-2024",
};

const strip = (html) =>
  html
    .replace(/<[^>]+>/g, " ")
    .replace(/&#8217;|&#039;|&rsquo;/g, "’")
    .replace(/&#8216;|&lsquo;/g, "‘")
    .replace(/&#8220;|&ldquo;/g, "“")
    .replace(/&#8221;|&rdquo;/g, "”")
    .replace(/&#8211;|&ndash;/g, "–")
    .replace(/&#8230;|&hellip;/g, "…")
    .replace(/&nbsp;/g, " ")
    .replace(/&amp;/g, "&")
    .replace(/&quot;/g, '"')
    .replace(/&lt;/g, "<")
    .replace(/&gt;/g, ">")
    .replace(/\s+/g, " ")
    .trim();

/** Titles come through as mathematical-bold codepoints (𝐀𝐁𝐀𝐂); NFKC folds
 *  them back to plain ASCII. */
const normalise = (s) => strip(s).normalize("NFKC");

/** The `content.rendered` field is a full Elementor page render, so every post
 *  arrives wrapped in site chrome. Two fixed artefacts to remove:
 *    - a header prefix: "Menu HOME EVENTS … <TITLE> ABAC <Month D, YYYY> 5:00 pm"
 *    - a "MORE UPDATES" block of teasers for other posts, at the end        */
const CHROME_PREFIX =
  /^.*?ABAC\s+(?:January|February|March|April|May|June|July|August|September|October|November|December)\s+\d{1,2},\s+\d{4}\s+\d{1,2}:\d{2}\s*(?:am|pm)\s*/i;

const dechrome = (p) => {
  const cut = p.replace(CHROME_PREFIX, "");
  return cut === p ? p : cut;
};

const paragraphs = (html) =>
  html
    .split(/<\/p>|<br\s*\/?>/i)
    .map(strip)
    .map(dechrome)
    .filter((p) => p.length > 1)
    .filter((p) => !/^MORE UPDATES\b/i.test(p));

async function download(url, dest) {
  const res = await fetch(url);
  if (!res.ok) throw new Error(`${res.status} ${url}`);
  await pipeline(Readable.fromWeb(res.body), createWriteStream(dest));
}

const posts = await fetch(
  `${SITE}/wp-json/wp/v2/posts?per_page=50&_embed=1`,
).then((r) => r.json());

await mkdir(IMG_DIR, { recursive: true });

const stories = [];
for (const p of posts) {
  const date = p.date.slice(0, 10);
  const slug = SLUGS[date] ?? p.slug;
  const src = p._embedded?.["wp:featuredmedia"]?.[0]?.source_url ?? null;

  let image = null;
  if (src) {
    image = `/img/stories/${slug}${path.extname(new URL(src).pathname)}`;
    await download(src, `public${image}`);
    console.log("downloaded", image);
  }

  const body = paragraphs(p.content.rendered).map(normalise);

  /** WordPress returns the whole article as the excerpt when no manual one was
   *  set, so derive a card-sized summary from the opening paragraph instead. */
  const lead = body[0] ?? "";
  const excerpt =
    lead.length <= 200 ? lead : lead.slice(0, 197).replace(/\s+\S*$/, "") + "…";

  stories.push({ slug, title: normalise(p.title.rendered), date, image, excerpt, body });
}

stories.sort((a, b) => b.date.localeCompare(a.date));

const file = `// GENERATED by scripts/migrate-wordpress.mjs — do not edit by hand.
// Source: ${SITE}/wp-json/wp/v2/posts (migrated ${new Date().toISOString().slice(0, 10)})

export type Story = {
  slug: string;
  title: string;
  date: string;
  image: string | null;
  excerpt: string;
  body: string[];
};

export const STORIES: Story[] = ${JSON.stringify(stories, null, 2)};
`;

await writeFile("content/stories.ts", file);
console.log(`\nwrote content/stories.ts — ${stories.length} stories`);
